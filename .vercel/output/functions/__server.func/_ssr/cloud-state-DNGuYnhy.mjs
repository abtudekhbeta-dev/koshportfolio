	const date = String(f.date || "");
	const sourceUrl = String(f.sourceUrl || "");
	if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || !(price > 0) || !/^https?:\/\//i.test(sourceUrl)) return null;
