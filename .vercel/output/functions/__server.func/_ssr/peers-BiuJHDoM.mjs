function tick(s) {
	return String(s || "").toUpperCase().replace(/\.(NS|BO)$/i, "");
}
function aliases(s) {
	const t = tick(s);
	return [
		t,
		t.replace(/-/g, "_").replace(/&/g, "_"),
		t.replace(/[-&]/g, "")
	];
}
