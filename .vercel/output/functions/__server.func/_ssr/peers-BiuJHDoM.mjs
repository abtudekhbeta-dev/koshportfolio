function sameBusinessPiles(rows, pack) {
	if (!pack?.symbols?.length) return [];
	const eq = rows.filter((r) => r.kind !== "commodity" && r.weight > 0);
	const byLine = /* @__PURE__ */ new Map();
	for (const r of eq) {
		const line = peerLineOf(r.symbol);
		if (!line) continue;
		const cur = byLine.get(line.label) || [];
		cur.push(r);
		byLine.set(line.label, cur);
	}
	const piles = [];
	for (const [label, list] of byLine) {
		const nodes = list.filter((r) => pack.symbols.some((s) => sameName(s, r.symbol)));
		if (nodes.length < 2) continue;
		const parent = nodes.map((_, i) => i);
		const find = (a) => parent[a] === a ? a : parent[a] = find(parent[a]);
		for (let i = 0; i < nodes.length; i++) for (let j = i + 1; j < nodes.length; j++) {
			const c = corrAt(pack, nodes[i].symbol, nodes[j].symbol);
			if (c != null && c >= .5) {
				const pa = find(i);
				const pb = find(j);
				if (pa !== pb) parent[pb] = pa;
			}
		}
		const groups = /* @__PURE__ */ new Map();
		for (let i = 0; i < nodes.length; i++) {
			const p = find(i);
			const g = groups.get(p) || [];
			g.push(nodes[i]);
			groups.set(p, g);
		}
		for (const g of groups.values()) {
			if (g.length < 2) continue;
			let min = 1;
			for (let i = 0; i < g.length; i++) for (let j = i + 1; j < g.length; j++) {
				const c = corrAt(pack, g[i].symbol, g[j].symbol);
				if (c != null) min = Math.min(min, c);
			}
			piles.push({
				line: label,
				names: [...g].sort((a, b) => b.weight - a.weight).map((r) => ({
					symbol: r.symbol,
					name: r.name,
					weight: r.weight
				})),
				minCorr: min
			});
		}
	}
	return piles.sort((a, b) => {
		const wa = a.names.reduce((s, n) => s + n.weight, 0);
		return b.names.reduce((s, n) => s + n.weight, 0) - wa;
	});
}
