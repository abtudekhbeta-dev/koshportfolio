/**
* One insight sentence when PE, ROCE and growth exist on the name and on peers.
* Never pads with a sector when the business line is missing.
*/
function peerInsight(mine, peers) {
	if (!mine) return null;
	const pe = mine.pe;
	const roce = mine.roce;
	const g = growthOf(mine);
	const withPe = peers.map((p) => p.pe).filter((n) => n != null && n > 0);
	const withRoce = peers.map((p) => p.roce).filter((n) => n != null && Number.isFinite(n));
	const withG = peers.map(growthOf).filter((n) => n != null && Number.isFinite(n));
	if (pe == null || !(pe > 0) || withPe.length < 2) return null;
	if (roce == null || withRoce.length < 2) return null;
	if (g == null || withG.length < 2) return null;
	const peMed = median(withPe);
	const roceMed = median(withRoce);
	const gMed = median(withG);
	if (peMed == null || roceMed == null || gMed == null || !(peMed > 0)) return null;
	const peGap = (pe / peMed - 1) * 100;
	const roceGap = roce - roceMed;
	const gGap = g - gMed;
	return `${Math.abs(peGap) < 8 ? "You are paying roughly in line with this business line" : peGap > 0 ? `You are paying ${peGap.toFixed(0)}% more than this business line` : `You are paying ${Math.abs(peGap).toFixed(0)}% less than this business line`} ${Math.abs(roceGap) < 2 && Math.abs(gGap) < 4 ? "for similar ROCE and growth." : `for ${roceGap >= 0 ? "+" : ""}${roceGap.toFixed(0)} pp ROCE and ${gGap >= 0 ? "+" : ""}${gGap.toFixed(0)} pp growth versus the same names.`} Not a cheap/expensive call on its own.`;
}
function corrAt(pack, a, b) {
	if (!pack) return null;
	const ia = pack.symbols.findIndex((s) => sameName(s, a));
	const ib = pack.symbols.findIndex((s) => sameName(s, b));
	if (ia < 0 || ib < 0) return null;
	return pack.matrix[ia][ib];
}
